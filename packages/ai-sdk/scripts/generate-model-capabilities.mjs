#!/usr/bin/env node
/**
 * generate-model-capabilities.mjs — compile `model-capabilities/models.json` into a
 * committed source module.
 *
 * WHY: `models.json` is the vendored models.dev catalog — ~290KB of descriptions,
 * benchmarks, and pricing that a prompt-assembly path has no use for. The SDK builds
 * with plain `tsc` (no bundler) and ships to the browser, so importing the raw JSON
 * would put all of it in the bundle to read two numbers per model. This script keeps
 * only `limit.context` / `limit.output` and writes:
 *
 *   - `src/providers/model-catalog.generated.ts`
 *
 * Keyed by the **unqualified** model id (`zhipuai/glm-5v-turbo` → `glm-5v-turbo`),
 * because hosts configure the bare model name far more often than the catalog's
 * `vendor/model` form, and the same model reached through OpenRouter, Ollama, or a
 * first-party API has the same window whatever prefix precedes it. That is only safe
 * while basenames are unique, so this script HARD-FAILS on a basename that two
 * catalog ids claim with different limits rather than silently picking one.
 *
 * The output is committed. Run via `pnpm generate:model-capabilities` (also part of
 * `pnpm build`); a unit test regenerates it and fails if the checked-in file is stale.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const pkgRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const catalogPath = join(pkgRoot, 'model-capabilities', 'models.json');
const tsOut = join(pkgRoot, 'src', 'providers', 'model-catalog.generated.ts');

/** Last path component of a catalog id (`zhipuai/glm-5v-turbo` → `glm-5v-turbo`). */
function unqualify(id) {
  return id.split('/').at(-1).toLowerCase();
}

/**
 * Reduce the raw catalog to `{ basename: { contextWindow, maxOutputTokens } }`.
 *
 * Entries without a positive context window are dropped: the catalog lists image and
 * audio endpoints (`gpt-image-1`, `whisper-*`) with `context: 0`, and a zero window
 * would make the budgeter divide by nothing. Entries with a context window but no
 * `limit.output` keep `null` — the consumer substitutes the provider floor rather than
 * inventing a reservation.
 */
export function buildCatalog(raw) {
  /** @type {Map<string, { contextWindow: number, maxOutputTokens: number | null, sources: string[] }>} */
  const byBasename = new Map();

  for (const [id, model] of Object.entries(raw)) {
    const contextWindow = model?.limit?.context;
    if (typeof contextWindow !== 'number' || contextWindow <= 0) continue;
    const rawOutput = model?.limit?.output;
    const maxOutputTokens = typeof rawOutput === 'number' && rawOutput > 0 ? rawOutput : null;

    const key = unqualify(id);
    const existing = byBasename.get(key);
    if (!existing) {
      byBasename.set(key, { contextWindow, maxOutputTokens, sources: [id] });
      continue;
    }
    if (existing.contextWindow !== contextWindow || existing.maxOutputTokens !== maxOutputTokens) {
      throw new Error(
        `models.json: two vendors claim the model name "${key}" with different limits ` +
          `(${existing.sources.join(', ')} vs ${id}). Basename keying is no longer safe — ` +
          `teach model-capabilities.ts to disambiguate before regenerating.`,
      );
    }
    existing.sources.push(id);
  }

  return byBasename;
}

/**
 * Quote a key only when it is not a plain identifier — matching Prettier's `quoteProps:
 * "as-needed"`, so the generated file is already formatted and the staleness test does not
 * fail the moment someone runs the formatter. `__proto__` is rejected outright: as an
 * object-literal key it would rewrite the prototype instead of adding a model.
 */
function renderKey(key) {
  if (key === '__proto__') {
    throw new Error(`models.json: refusing to emit the reserved key "${key}"`);
  }
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : `'${key}'`;
}

function renderModule(byBasename) {
  const lines = [...byBasename.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(
      ([key, { contextWindow, maxOutputTokens }]) =>
        `  ${renderKey(key)}: { contextWindow: ${contextWindow}, maxOutputTokens: ${maxOutputTokens} },`,
    );

  return `// AUTO-GENERATED by scripts/generate-model-capabilities.mjs — DO NOT EDIT BY HAND.
// Source: model-capabilities/models.json (vendored models.dev catalog).
// Regenerate with \`pnpm --filter @framepilot/ai-sdk generate:model-capabilities\`.

/** The two figures the budgeter needs, distilled from one catalog entry. */
export interface CatalogLimits {
  /** Total input tokens the model accepts for one request. Always positive. */
  readonly contextWindow: number;
  /** The model's documented max output, or \`null\` when the catalog omits it. */
  readonly maxOutputTokens: number | null;
}

/**
 * Every catalog model with a usable context window, keyed by its unqualified id
 * (the part after the last \`/\`). Basenames are unique across vendors; the generator
 * fails the build if that ever stops being true.
 */
export const MODEL_CATALOG: Readonly<Record<string, CatalogLimits>> = Object.freeze({
${lines.join('\n')}
});
`;
}

/** Build the module text from the vendored catalog, without touching disk output. */
export function renderCatalogModule(rawJson = readFileSync(catalogPath, 'utf8')) {
  return renderModule(buildCatalog(JSON.parse(rawJson)));
}

const isDirectRun = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isDirectRun) {
  const source = renderCatalogModule();
  writeFileSync(tsOut, source, 'utf8');
  const count = source.split('\n').filter((line) => /^ {2}\S+: \{ contextWindow/.test(line)).length;
  console.log(`generate-model-capabilities: wrote ${count} models to ${tsOut}`);
}
